/** Polština: 1 aplikacja, 2–4 aplikacje (kromě 12–14), jinak aplikacji. */
function plApps(n: number): string {
  if (n === 1) return "aplikacja";
  const lastTwo = n % 100;
  const last = n % 10;
  if (last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14)) return "aplikacje";
  return "aplikacji";
}

